#include<stdio.h>
//#include<math.h> 
int main() {
    int a,b;
    printf("Enter value of a:\n");
    scanf("%d",&a);

    printf("Enter value of b:\n");
    scanf("%d",&b);
    printf("Sum is:%d\n", a+b); //Addition of two numbers.
    printf("Difference is :%d\n", a-b); //Subtraction of two numbers.
    printf("Multiplication is :%d\n", a*b); //Subtraction of two numbers.

    printf("Modulus is :%d\n", a%b); // Modulus of two numbers.
    printf("Division is :%d\n", a/b); //Divisionion of two numbers.
    printf("%d\n", 3<4 && 7>6); // AND operation two numbers.
    printf("%d\n", 7>6 || 6>7); // OR operation two numbers.
    printf("Thankyou\n");
    return 0;
}


       
       
