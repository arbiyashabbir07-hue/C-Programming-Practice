//Rational operators i.e(==,<, >,  >=, <=,  !=)
// True:1 False:0
#include<stdio.h>
#include<math.h>
int main(){
    printf("%d\n" ,3<4);
    printf("%d\n" ,1<6);
    printf("%d\n" ,7>85);
    printf("%d\n" ,2007>2006);
    printf("%d\n" ,3<4);
    printf("%d\n" ,3!=4); 
    printf("%d\n" , 1!=2);
    printf("%d\n" ,1==1);
    printf("%d\n", 2007 != 2006);
    return 45; //We can write any positive integer insted of 0.
}

